#!/usr/bin/env bash
set -euo pipefail

: "${POSTGRES_USER:?POSTGRES_USER is required}"
: "${POSTGRES_DB:?POSTGRES_DB is required}"
: "${SIGEM_APP_PASSWORD:?SIGEM_APP_PASSWORD is required}"

psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v app_password="$SIGEM_APP_PASSWORD" -v db_name="$POSTGRES_DB" -v migration_role="$POSTGRES_USER" <<'SQL'
SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'sigem_app') AS role_exists \gset
\if :role_exists
ALTER ROLE sigem_app WITH LOGIN PASSWORD :'app_password';
\else
CREATE ROLE sigem_app LOGIN PASSWORD :'app_password';
\endif
ALTER ROLE sigem_app NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
ALTER ROLE sigem_app SET search_path = public;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE ALL ON DATABASE :"db_name" FROM sigem_app;
GRANT CONNECT ON DATABASE :"db_name" TO sigem_app;
GRANT USAGE ON SCHEMA public TO sigem_app;
ALTER DEFAULT PRIVILEGES FOR ROLE :"migration_role" IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO sigem_app;
ALTER DEFAULT PRIVILEGES FOR ROLE :"migration_role" IN SCHEMA public GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO sigem_app;
ALTER DEFAULT PRIVILEGES FOR ROLE :"migration_role" IN SCHEMA public GRANT EXECUTE ON FUNCTIONS TO sigem_app;
SQL

psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" <<'SQL'
REVOKE CREATE ON SCHEMA public FROM sigem_app;
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM sigem_app;
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM sigem_app;
REVOKE ALL PRIVILEGES ON ALL FUNCTIONS IN SCHEMA public FROM sigem_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO sigem_app;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO sigem_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO sigem_app;
SQL
